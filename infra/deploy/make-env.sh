#!/usr/bin/env bash
# Writes infra/deploy/.env.prod and seaweedfs-s3.json for the public demo: fresh secrets for
# everything internal, and only the external service keys (Nebius, Tavily, Telegram) copied from the
# local .env. Run locally, then copy both files to the server (scp; chmod 600). Never commit them.
# Usage: infra/deploy/make-env.sh <domain>     e.g. crowdshield.3-91-20-7.sslip.io
set -euo pipefail
cd "$(dirname "$0")"
DOMAIN="${1:?usage: make-env.sh <domain>}"
LOCAL=../../.env
get() { grep -E "^$1=" "$LOCAL" | head -1 | cut -d= -f2- || true; }
hex() { openssl rand -hex "$1"; }

PG=$(hex 24)
S3_KEY=cs$(hex 6)
S3_SECRET=$(hex 24)
umask 077
cat > .env.prod <<ENV
# Generated by make-env.sh for https://$DOMAIN on $(date -u +%F). Secret: keep out of git.
DOMAIN=$DOMAIN
POSTGRES_PASSWORD=$PG
DATABASE_URL=postgres://crowdshield:$PG@postgres:5432/crowdshield
REDIS_URL=redis://redis:6379/0
S3_ENDPOINT=http://s3:8333
S3_REGION=us-east-1
S3_ACCESS_KEY=$S3_KEY
S3_SECRET_KEY=$S3_SECRET
S3_BUCKET_EVIDENCE=evidence
S3_BUCKET_INVOICES=invoices
IDENTIFIER_HMAC_PEPPER=$(hex 32)
IDENTIFIER_ENC_KEY=$(hex 32)
JWT_SECRET=$(hex 32)
AUTH_SECRET=$(hex 32)
BOT_API_KEY=$(hex 24)
ML_API_KEY=$(hex 24)
BANK_PARTNER_KEY=$(hex 24)
BANK_PARTNER_ORG=Nusa Digital Bank
# this VM's database holds synthetic demo data only: seeding and reset are allowed
DEMO_DATABASE=yes
# demo logins are published for judges; synthetic data only
SEED_DEMO_PASSWORD=$(get SEED_DEMO_PASSWORD || true)
API_URL=http://api:4020
API_PORT=4020
ML_GATEWAY_URL=http://ml:8020
WEB_URL=https://$DOMAIN
PUBLIC_BOT_URL=$(get PUBLIC_BOT_URL)
TRUST_PROXY=uniquelocal
NEBIUS_API_KEY=$(get NEBIUS_API_KEY)
NEBIUS_BASE_URL=$(get NEBIUS_BASE_URL)
NEBIUS_MODEL_TEXT=$(get NEBIUS_MODEL_TEXT)
NEBIUS_MODEL_VISION=$(get NEBIUS_MODEL_VISION)
NEBIUS_MODEL_EMBEDDING=$(get NEBIUS_MODEL_EMBEDDING)
TAVILY_API_KEY=$(get TAVILY_API_KEY)
TELEGRAM_BOT_TOKEN=$(get TELEGRAM_BOT_TOKEN)
ENV
cat > seaweedfs-s3.json <<JSON
{
  "identities": [
    {
      "name": "crowdshield",
      "credentials": [{ "accessKey": "$S3_KEY", "secretKey": "$S3_SECRET" }],
      "actions": ["Admin", "Read", "Write", "List", "Tagging"]
    }
  ]
}
JSON
grep -q '^NEBIUS_API_KEY=.\+' .env.prod || echo "warning: NEBIUS_API_KEY missing in $LOCAL"
grep -q '^TELEGRAM_BOT_TOKEN=.\+' .env.prod || echo "warning: TELEGRAM_BOT_TOKEN missing in $LOCAL"
echo "wrote infra/deploy/.env.prod and seaweedfs-s3.json for $DOMAIN"
